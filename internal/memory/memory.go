// Package memory is the shared memory store both agents read and write
// through `mom mem`. Each memory is one markdown file holding one fact, with
// frontmatter; each scope keeps a generated INDEX.md that is loaded into
// every session by a SessionStart hook.
//
//	~/.mom/memory/user/<name>.md               applies everywhere
//	~/.mom/memory/projects/<project>/<name>.md  applies in one repo
package memory

import (
	"bufio"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
	"time"

	"github.com/gbikhazi20/mom/internal/fsx"
	"github.com/gbikhazi20/mom/internal/project"
)

var Types = []string{"user", "feedback", "project", "reference"}

type Memory struct {
	Name        string `json:"name"`
	Description string `json:"description"`
	Type        string `json:"type"`
	Created     string `json:"created,omitempty"`
	Updated     string `json:"updated,omitempty"`
	Source      string `json:"source,omitempty"` // who wrote it: claude, codex, import, ...
	Body        string `json:"body,omitempty"`
	Scope       Scope  `json:"scope"`
	Path        string `json:"path,omitempty"`
}

// Scope is "user" or a project ID.
type Scope struct {
	Project string `json:"project,omitempty"` // empty means user scope
}

func User() Scope             { return Scope{} }
func Project(id string) Scope { return Scope{Project: id} }
func (s Scope) IsUser() bool  { return s.Project == "" }
func (s Scope) String() string {
	if s.IsUser() {
		return "user"
	}
	return "project:" + s.Project
}

type Store struct{ Root string }

func (st Store) Dir(s Scope) string {
	if s.IsUser() {
		return filepath.Join(st.Root, "user")
	}
	return filepath.Join(st.Root, "projects", s.Project)
}

// Projects lists project IDs that have memories.
func (st Store) Projects() []string {
	return fsx.Entries(filepath.Join(st.Root, "projects"))
}

func (st Store) List(s Scope) ([]Memory, error) {
	dir := st.Dir(s)
	var out []Memory
	for _, n := range fsx.Entries(dir) {
		if !strings.HasSuffix(n, ".md") || n == "INDEX.md" {
			continue
		}
		m, err := st.read(filepath.Join(dir, n), s)
		if err != nil {
			return nil, err
		}
		out = append(out, m)
	}
	sort.Slice(out, func(i, j int) bool { return out[i].Name < out[j].Name })
	return out, nil
}

func (st Store) Get(s Scope, name string) (Memory, error) {
	return st.read(filepath.Join(st.Dir(s), Slug(name)+".md"), s)
}

func (st Store) read(path string, s Scope) (Memory, error) {
	b, err := os.ReadFile(path)
	if err != nil {
		return Memory{}, err
	}
	m := Parse(string(b))
	if m.Name == "" {
		m.Name = strings.TrimSuffix(filepath.Base(path), ".md")
	}
	m.Scope, m.Path = s, path
	return m, nil
}

// Save creates or updates a memory and refreshes its scope's index.
// Updating keeps the original created date.
func (st Store) Save(m Memory) (Memory, error) {
	m.Name = Slug(m.Name)
	if m.Name == "" {
		return m, fmt.Errorf("name is required")
	}
	if strings.TrimSpace(m.Description) == "" {
		return m, fmt.Errorf("description is required (it's what decides relevance later)")
	}
	if !validType(m.Type) {
		return m, fmt.Errorf("type must be one of %s", strings.Join(Types, ", "))
	}
	today := time.Now().Format("2006-01-02")
	if prev, err := st.Get(m.Scope, m.Name); err == nil && prev.Created != "" {
		m.Created = prev.Created
	}
	if m.Created == "" {
		m.Created = today
	}
	if m.Updated == "" {
		m.Updated = today
	}
	m.Path = filepath.Join(st.Dir(m.Scope), m.Name+".md")
	if err := os.MkdirAll(filepath.Dir(m.Path), 0o755); err != nil {
		return m, err
	}
	if err := fsx.WriteAtomic(m.Path, []byte(Format(m))); err != nil {
		return m, err
	}
	return m, st.Reindex(m.Scope)
}

// Remove moves a memory into backupDir and refreshes the index.
func (st Store) Remove(s Scope, name, backupDir string) (string, error) {
	path := filepath.Join(st.Dir(s), Slug(name)+".md")
	if !fsx.Exists(path) {
		return "", fmt.Errorf("no memory %q in %s", name, s)
	}
	dst := filepath.Join(backupDir, "memory", s.String(), filepath.Base(path))
	if err := fsx.Move(path, dst); err != nil {
		return "", err
	}
	return dst, st.Reindex(s)
}

// Reindex rewrites INDEX.md for a scope (removing it if the scope is empty).
func (st Store) Reindex(s Scope) error {
	ms, err := st.List(s)
	if err != nil {
		return err
	}
	path := filepath.Join(st.Dir(s), "INDEX.md")
	if len(ms) == 0 {
		os.Remove(path)
		os.Remove(st.Dir(s))
		return nil
	}
	var b strings.Builder
	fmt.Fprintf(&b, "# Memory index: %s\n<!-- generated by mom; change memories with `mom mem` -->\n\n", s)
	for _, m := range ms {
		fmt.Fprintf(&b, "- [%s](%s.md) (%s) — %s\n", m.Name, m.Name, m.Type, oneLine(m.Description))
	}
	return fsx.WriteAtomic(path, []byte(b.String()))
}

// Find looks a name up in the given scopes, in order.
func (st Store) Find(name string, scopes ...Scope) (Memory, error) {
	for _, s := range scopes {
		if m, err := st.Get(s, name); err == nil {
			return m, nil
		}
	}
	return Memory{}, fmt.Errorf("no memory named %q", Slug(name))
}

// AllScopes is the user scope followed by every project.
func (st Store) AllScopes() []Scope {
	out := []Scope{User()}
	for _, p := range st.Projects() {
		out = append(out, Project(p))
	}
	return out
}

// Search ranks memories in scopes by keyword relevance (same scoring as
// recall, but every word counts and no minimum applies: the caller asked).
func (st Store) Search(query string, scopes ...Scope) ([]Memory, error) {
	all, err := st.listAll(scopes)
	if err != nil {
		return nil, err
	}
	var out []Memory
	for _, sc := range score(all, query) {
		out = append(out, sc.m)
	}
	return out, nil
}

// ScopesFor returns the scopes visible from dir: user, plus its project.
func ScopesFor(dir string) ([]Scope, *project.Info) {
	scopes := []Scope{User()}
	if info, ok := project.Detect(dir); ok {
		scopes = append(scopes, Project(info.ID))
		return scopes, &info
	}
	return scopes, nil
}

// --- file format ---

// Format renders a memory file. Frontmatter stays flat and simple.
func Format(m Memory) string {
	var b strings.Builder
	b.WriteString("---\n")
	fmt.Fprintf(&b, "name: %s\n", m.Name)
	fmt.Fprintf(&b, "description: %s\n", quoteIfNeeded(oneLine(m.Description)))
	fmt.Fprintf(&b, "type: %s\n", m.Type)
	if m.Created != "" {
		fmt.Fprintf(&b, "created: %s\n", m.Created)
	}
	if m.Updated != "" {
		fmt.Fprintf(&b, "updated: %s\n", m.Updated)
	}
	if m.Source != "" {
		fmt.Fprintf(&b, "source: %s\n", m.Source)
	}
	b.WriteString("---\n\n")
	b.WriteString(strings.TrimSpace(m.Body))
	b.WriteString("\n")
	return b.String()
}

var fmKeyRE = regexp.MustCompile(`^(\s*)([A-Za-z_]+):\s*(.*)$`)

// Parse reads mom's format and Claude Code's auto-memory format (which
// nests type under metadata:).
func Parse(text string) Memory {
	var m Memory
	if !strings.HasPrefix(text, "---\n") {
		m.Body = strings.TrimSpace(text)
		return m
	}
	rest := text[4:]
	end := strings.Index(rest, "\n---")
	if end < 0 {
		m.Body = strings.TrimSpace(text)
		return m
	}
	sc := bufio.NewScanner(strings.NewReader(rest[:end]))
	for sc.Scan() {
		g := fmKeyRE.FindStringSubmatch(sc.Text())
		if g == nil {
			continue
		}
		val := unquote(strings.TrimSpace(g[3]))
		switch g[2] {
		case "name":
			if g[1] == "" {
				m.Name = val
			}
		case "description":
			m.Description = val
		case "type":
			m.Type = val
		case "created":
			m.Created = val
		case "updated":
			m.Updated = val
		case "modified":
			if m.Updated == "" && len(val) >= 10 {
				m.Updated = val[:10]
			}
		case "source":
			m.Source = val
		}
	}
	body := rest[end+4:]
	m.Body = strings.TrimSpace(strings.TrimPrefix(body, "\n"))
	return m
}

func validType(t string) bool {
	for _, x := range Types {
		if t == x {
			return true
		}
	}
	return false
}

var nonSlug = regexp.MustCompile(`[^a-z0-9]+`)

// Slug normalises a memory name: lowercase, dashes, no extension.
func Slug(s string) string {
	s = strings.TrimSuffix(strings.ToLower(strings.TrimSpace(s)), ".md")
	return strings.Trim(nonSlug.ReplaceAllString(s, "-"), "-")
}

func oneLine(s string) string { return strings.Join(strings.Fields(s), " ") }

func quoteIfNeeded(s string) string {
	if strings.ContainsAny(s, ":#\"'") || strings.HasPrefix(s, "-") || strings.HasPrefix(s, "[") {
		return `"` + strings.ReplaceAll(strings.ReplaceAll(s, `\`, `\\`), `"`, `\"`) + `"`
	}
	return s
}

func unquote(s string) string {
	if len(s) >= 2 && s[0] == '"' && s[len(s)-1] == '"' {
		s = s[1 : len(s)-1]
		return strings.ReplaceAll(strings.ReplaceAll(s, `\"`, `"`), `\\`, `\`)
	}
	if len(s) >= 2 && s[0] == '\'' && s[len(s)-1] == '\'' {
		return strings.ReplaceAll(s[1:len(s)-1], "''", "'")
	}
	return s
}
